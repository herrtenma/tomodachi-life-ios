"""Static game image: the four native NSOs as segments of the nxrt binary (no JIT, iOS).

The Mac loader copies the NSOs into fresh memory, patches them and makes the text executable;
iOS only allows that with JIT. This writes an assembly file that puts each module in two Mach-O
segments of the signed binary, in the loader's layout (rtld | main | subsdk9 | sdk, 16 KB-aligned):

    __NX<i>T  r-x  [0, PAGE_UP(text))        text (+ the start of ro sharing its last page)
    __NX<i>D  rw-  [PAGE_UP(text), span)     ro, data, bss (zerofill); rtld relocates it in place

Code-relative references (adrp, ldr literal) stay valid because the whole binary slides as one
block. Code patches are applied here (build time) instead of by the loader:
  - host hooks: the function's first 16 bytes -> adrp x16, sym@PAGE ; add x16, x16, sym@PAGEOFF ; br x16 ; nop
  - --fps60: the min present interval patches of loader.c NXRT_MININTERVAL (n = 1)

Usage: embed.py <work dir> <out.s> [--fps60]
       embed.py --empty <port/layout.json> <out.s>
--empty builds the slots without the game: every game byte is zero (only the hook stubs, our code, are there), in the
same layout. That is the app that is distributed; the packager app (nx-packager) fills the slots in the Mach-O from the
user's own game files and the port's patch (tools/nxrecomp/mkpack.py).
Link with -Wl,-segprot,__NX<i>T,rx,rx and -Wl,-segprot,__NX<i>D,rw,rw (embed.py prints the flags with --ldflags)."""
import os
import struct
import sys

PAGE = 0x4000
MODULES = ["rtld", "main", "subsdk9", "sdk"]
# (module, offset, host symbol): same list as loader.c `hooks[]`
HOOKS = [("sdk", 0x502d10, "nx_nvn_bootstrap_loader"),
         # widescreen (ui_touch.c nx_wide_setup; inert until configured at run time): UI cameras, engine crop
         ("main", 0x46c080, "nx_ui_ortho"), ("main", 0x6ec3c0, "nx_ui_persp"), ("main", 0x46e974, "nx_wide_crop")]
# (module, offset, original word, patched word): loader.c NXRT_MININTERVAL with n = 1
FPS60 = [
    ("main", 0x90378c, 0xD2800048, 0xD2800028),   # mov x8, #1     main() init
    ("main", 0x1d2af84, 0xD2800048, 0xD2800028),  # mov x8, #1     reset to 2/3
    ("main", 0x1d2af90, 0x52800048, 0x52800028),  # mov w8, #1     ctl+0x44 copy
    ("main", 0x1b45f04, 0x52800041, 0x52800021),  # mov w1, #1     UGC editor exit
    ("main", 0x187cdc4, 0x52800089, 0x52800029),  # mov w9, #1     script setter cap
    ("main", 0x187cdd8, 0x7100111F, 0x7100051F),  # cmp w8, #1
]


def page_up(x):
    return (x + PAGE - 1) & ~(PAGE - 1)


def read_nso(path):
    with open(path, "rb") as f:
        raw = f.read()
    if raw[:4] != b"NSO0":
        raise SystemExit(f"{path}: not an NSO")
    segs = [struct.unpack_from("<III", raw, 0x10 + i * 0x10) for i in range(3)]   # file off, mem off, size
    bss = struct.unpack_from("<I", raw, 0x3C)[0]
    flags = struct.unpack_from("<I", raw, 0x0C)[0]
    if flags & 7:
        raise SystemExit(f"{path}: compressed segments (flags {flags:#x}); native NSOs are uncompressed")
    img = bytearray(max(m + s for _, m, s in segs))
    for off, mem, size in segs:
        img[mem:mem + size] = raw[off:off + size]
    return img, segs, bss


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    opts = {a for a in sys.argv[1:] if a.startswith("--")}
    if "--ldflags" in opts:
        print(" ".join(f"-Wl,-segprot,__NX{i}T,rx,rx -Wl,-segprot,__NX{i}D,rw,rw" for i in range(len(MODULES))))
        return
    if "--empty" in opts:
        return empty(*args)
    work, out = args
    bindir = os.path.join(os.path.dirname(os.path.abspath(out)), "image")
    os.makedirs(bindir, exist_ok=True)
    patches = {m: {} for m in MODULES}
    if "--fps60" in opts:
        for mod, off, old, new in FPS60:
            patches[mod][off] = (old, new)
    s = ["// Generated by tools/nxrecomp/embed.py: the game's native NSOs as signed segments. Do not edit.\n"]
    info = []
    for i, name in enumerate(MODULES):
        img, segs, bss = read_nso(os.path.join(work, f"{name}.native.nso"))
        info.append((segs[0][2], segs[1][1], segs[1][2], segs[2][1], segs[2][2], bss, page_up(len(img) + bss)))
        for off, (old, new) in patches[name].items():
            cur = struct.unpack_from("<I", img, off)[0]
            if cur != old:
                raise SystemExit(f"{name}+{off:#x}: expected {old:#x}, found {cur:#x}")
            struct.pack_into("<I", img, off, new)
        text_size = segs[0][2]
        tend = page_up(text_size)
        span = page_up(len(img) + bss)
        hooks = sorted((off, sym) for mod, off, sym in HOOKS if mod == name)
        if any(off + 16 > text_size for off, _ in hooks):
            raise SystemExit(f"{name}: hook outside text")
        # Binary blobs (the assembler includes them with .incbin)
        tpath = os.path.join(bindir, f"{name}.text.bin")
        dpath = os.path.join(bindir, f"{name}.data.bin")
        with open(tpath, "wb") as f:
            f.write(bytes(img[:tend]) + bytes(max(0, tend - len(img))))
        with open(dpath, "wb") as f:
            f.write(bytes(img[tend:]))
        s.append(f"\n// {name}: text {text_size:#x}, image {len(img):#x}, bss {bss:#x}, span {span:#x}\n")
        s.append(f".section __NX{i}T,__text,regular,pure_instructions\n.p2align 14\n")
        s.append(f".globl _nx_img_{name}\n_nx_img_{name}:\n")
        at = 0
        for off, sym in hooks:
            if off > at:
                s.append(f'.incbin "{tpath}", {at:#x}, {off - at:#x}\n')
            s.append(f"adrp x16, _{sym}@PAGE\nadd x16, x16, _{sym}@PAGEOFF\nbr x16\nnop\n")
            at = off + 16
        s.append(f'.incbin "{tpath}", {at:#x}, {tend - at:#x}\n')
        s.append(f".section __NX{i}D,__data\n.p2align 14\n.globl _nx_img_{name}_data\n_nx_img_{name}_data:\n")
        if len(img) > tend:
            s.append(f'.incbin "{dpath}"\n')
        zf = span - max(len(img), tend)
        if zf:
            s.append(f".zerofill __NX{i}D,__bss,_nx_img_{name}_bss,{zf:#x},0\n")
    # loader.c: per module text size, ro off/size, data off/size, bss, span; then flags (bit 0 = 60 fps)
    s.append("\n.section __DATA,__const\n.p2align 3\n.globl _nx_img_info\n_nx_img_info:\n")
    for row in info:
        s.append(".quad " + ", ".join(f"{v:#x}" for v in row) + "\n")
    s.append(f".quad {1 if '--fps60' in opts else 0}\n")
    with open(out, "w") as f:
        f.write("".join(s))
    print(f"embed: wrote {out} ({'60 fps' if '--fps60' in opts else '30 fps'} build)")


def empty(layout_path, out):
    """The slots with zeros where the game goes (see --empty above)."""
    import json
    layout = {m["name"]: m for m in json.load(open(layout_path))}
    s = ["// Generated by tools/nxrecomp/embed.py --empty: slots for the game's native NSOs, filled by the packager. Do not edit.\n"]
    info = []
    for i, name in enumerate(MODULES):
        m = layout[name]
        text_size, size, bss = m["text_size"], m["image_size"], m["bss"]
        info.append((text_size, m["ro_off"], m["ro_size"], m["data_off"], m["data_size"], bss, page_up(size + bss)))
        tend, span = page_up(text_size), page_up(size + bss)
        hooks = sorted((off, sym) for mod, off, sym in HOOKS if mod == name)
        if sorted((h["offset"], h["symbol"]) for h in m["hooks"]) != hooks:
            raise SystemExit(f"{name}: layout.json hooks differ from HOOKS (rerun mkpack.py)")
        s.append(f"\n// {name}: text {text_size:#x}, image {size:#x}, bss {bss:#x}, span {span:#x}\n")
        s.append(f".section __NX{i}T,__text,regular,pure_instructions\n.p2align 14\n")
        s.append(f".globl _nx_img_{name}\n_nx_img_{name}:\n")
        at = 0
        for off, sym in hooks:
            if off > at:
                s.append(f".space {off - at:#x}\n")
            s.append(f"adrp x16, _{sym}@PAGE\nadd x16, x16, _{sym}@PAGEOFF\nbr x16\nnop\n")
            at = off + 16
        s.append(f".space {tend - at:#x}\n")
        s.append(f".section __NX{i}D,__data\n.p2align 14\n.globl _nx_img_{name}_data\n_nx_img_{name}_data:\n")
        if size > tend:
            s.append(f".space {size - tend:#x}\n")
        zf = span - max(size, tend)
        if zf:
            s.append(f".zerofill __NX{i}D,__bss,_nx_img_{name}_bss,{zf:#x},0\n")
    s.append("\n.section __DATA,__const\n.p2align 3\n.globl _nx_img_info\n_nx_img_info:\n")
    for row in info:
        s.append(".quad " + ", ".join(f"{v:#x}" for v in row) + "\n")
    s.append(".quad 0\n")
    with open(out, "w") as f:
        f.write("".join(s))
    print(f"embed: wrote {out} (empty slots)")


if __name__ == "__main__":
    main()
